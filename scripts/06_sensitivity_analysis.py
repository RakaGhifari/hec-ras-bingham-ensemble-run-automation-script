def load_validation_data(
    validation_csv: Path,
) -> pd.DataFrame:
    """
    Load and validate the spatial validation results.

    Only rows corresponding to the configured primary depth threshold
    are retained.
    """

    if not validation_csv.exists():
        raise FileNotFoundError(
            f"Spatial validation CSV not found:\n"
            f"{validation_csv}"
        )

    df = pd.read_csv(
        validation_csv
    )

    # ------------------------------------------------------------------
    # Validate required columns
    # ------------------------------------------------------------------

    missing = [
        column
        for column in REQUIRED_COLUMNS
        if column not in df.columns
    ]

    if missing:
        raise ValueError(
            "Missing required columns in spatial validation CSV:\n"
            f"{missing}"
        )

    # ------------------------------------------------------------------
    # Select the primary threshold
    # ------------------------------------------------------------------

    df = df[
        np.isclose(
            df["Threshold_m"],
            PRIMARY_DEPTH_THRESHOLD,
        )
    ].copy()

    if df.empty:
        raise ValueError(
            "No spatial validation records were found for "
            f"the primary depth threshold "
            f"{PRIMARY_DEPTH_THRESHOLD} m."
        )

    # ------------------------------------------------------------------
    # Sort by Run
    # ------------------------------------------------------------------

    df["Run"] = (
        df["Run"]
        .astype(int)
    )

    df = (
        df
        .sort_values("Run")
        .reset_index(drop=True)
    )

    # ------------------------------------------------------------------
    # Validate duplicate Run IDs
    # ------------------------------------------------------------------

    if df["Run"].duplicated().any():

        duplicated = (
            df.loc[
                df["Run"].duplicated(),
                "Run",
            ]
            .tolist()
        )

        raise ValueError(
            "Duplicate Run IDs found in the primary-threshold "
            "spatial validation data:\n"
            f"{duplicated}"
        )

    # ------------------------------------------------------------------
    # Validate numerical data
    # ------------------------------------------------------------------

    numeric_columns = [
        "IoU",
        *SENSITIVITY_PARAMETERS,
    ]

    for column in numeric_columns:

        df[column] = pd.to_numeric(
            df[column],
            errors="coerce",
        )

    if df[numeric_columns].isna().any().any():

        invalid_counts = (
            df[numeric_columns]
            .isna()
            .sum()
        )

        invalid_counts = (
            invalid_counts[
                invalid_counts > 0
            ]
        )

        raise ValueError(
            "Missing or non-numeric values were found in "
            "the primary-threshold data:\n"
            f"{invalid_counts.to_dict()}"
        )

    # ------------------------------------------------------------------
    # Validate finite values
    # ------------------------------------------------------------------

    values = df[
        numeric_columns
    ].to_numpy(
        dtype=float
    )

    if not np.isfinite(values).all():

        raise ValueError(
            "Non-finite values were found in the "
            "sensitivity-analysis data."
        )

    return df


