# RESIDUALIZE
# ======================================================================

def residualize(
    y: np.ndarray,
    controls: np.ndarray,
) -> np.ndarray:
    """
    Remove the linear contribution of control variables from y.

    An intercept is included in the least-squares model.
    """

    controls = np.asarray(
        controls,
        dtype=float,
    )

    y = np.asarray(
        y,
        dtype=float,
    )

    if controls.ndim == 1:
        controls = controls.reshape(
            -1,
            1,
        )

    A = np.column_stack(
        [
            np.ones(
                len(controls)
            ),
            controls,
        ]
    )

    beta = np.linalg.lstsq(
        A,
        y,
        rcond=None,
    )[0]

    return (
        y
        - A @ beta
    )


# ======================================================================
# CALCULATE CORRELATIONS
# ======================================================================

def calculate_correlations(
    X: np.ndarray,
    y: np.ndarray,
    parameters: list[str],
) -> pd.DataFrame:
    """
    Calculate Pearson, Spearman, and Kendall correlations.
    """

    rows = []

    for i, parameter in enumerate(
        parameters
    ):

        x = X[:, i]

        pearson = pearsonr(
            x,
            y,
        )

        spearman = spearmanr(
            x,
            y,
        )

        kendall = kendalltau(
            x,
            y,
        )

        rows.append(
            {
                "Parameter": parameter,
                "Pearson_r": pearson.statistic,
                "Pearson_p": pearson.pvalue,
                "Spearman_rho": spearman.statistic,
                "Spearman_p": spearman.pvalue,
                "Kendall_tau": kendall.statistic,
                "Kendall_p": kendall.pvalue,
            }
        )

    return pd.DataFrame(
        rows
    )


